import { writeFileSync } from 'node:fs';
import { listRoutes } from '../server/http/framework';
import '../server/http/routes';

const groups = new Map<string, ReturnType<typeof listRoutes>>();
for (const r of listRoutes()) { const g = r.path.split('/')[1]; groups.set(g, [...(groups.get(g) ?? []), r]); }
const out = ['<!-- Generated by `npx tsx scripts/gen-api-docs.ts` from the live route table. Do not edit by hand. -->', '', '# Endpoint reference', '',
  'Base path `/api/v1`. All requests and responses are JSON unless noted. `public` endpoints need no session; every other endpoint requires the `plumeo_session` cookie and is authorised server-side per request. See [api.md](api.md) for conventions.', ''];
for (const [g, rs] of groups) {
  out.push(`## ${g}`, '', '| Method | Path | Auth |', '|---|---|---|', ...rs.map((r) => `| ${r.method} | \`${r.path}\` | ${r.public ? 'public' : 'session'}${r.idempotent ? ' · Idempotency-Key' : ''} |`), '');
}
writeFileSync('docs/endpoints.md', out.join('\n'));
console.log(`Wrote docs/endpoints.md (${listRoutes().length} endpoints)`);
